# Variables en Python
# Declaracion e inicializacion de variables
edad = 28
altura = 1.65
pais = 'México'

# Acceder a las variables
print('Edad:', edad)
print('Altura:', altura)
print('País:', pais)    

# Modificar las variables
edad = 30
altura = 1.68
pais = 'Argentina'

# Acceder a las variables modificadas
print('Edad modificada:', edad) 
print('Altura modificada:', altura)
print('País modificado:', pais)

# En Python el tipo es dinámico (puede cambiar)
edad = 'treinta'
altura = 'uno punto sesenta y ocho'
pais = 'Argentina'
print('Edad como cadena:', edad)
print('Altura como cadena:', altura)
print('País como cadena:', pais)

